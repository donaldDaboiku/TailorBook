const defaultTemplates: Record<string, string> = {
  female: 'Female',
  male: 'Male',
  child: 'Child',
}

export function translatedFieldLabel(
  t: I18nValue['t'],
  key: string,
  label: string,
): string {
  if (!defaultFieldLabels[key]?.includes(label)) {
    return label
  }

  return t(`measure.${key}`)
}

export function translatedTemplateName(
  t: I18nValue['t'],
  slug: string,
  name: string,
): string {
  if (defaultTemplates[slug] !== name) {
    return name
  }

  return t(`measure.template.${slug}`)
}

export function LanguageSelect() {
  const { lang, setLang, t } = useI18n()

  return (
    <label>
      {t('language')}
      <select
        value={lang}
        onChange={(event) => setLang(event.target.value as Lang)}
      >
        {languages.map((item) => (
          <option key={item.id} value={item.id}>
            {item.name}
          </option>
        ))}
      </select>
    </label>
  )
}
